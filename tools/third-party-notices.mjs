#!/usr/bin/env node
/** Reproduce notices from the lock and the installed, version-matched licenses. */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const read = (file) =>
  JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
const lock = read("package-lock.json"),
  workspace = read("package.json"),
  plugin = read("plugin/package.json");
const rows = Object.entries(lock.packages)
  .filter(([file]) => file)
  .map(([file, entry]) => {
    const meta = read(`${file}/package.json`);
    if (
      meta.version !== entry.version ||
      meta.license !== entry.license ||
      typeof meta.license !== "string"
    )
      throw Error(
        `Installed dependency differs from lock: ${file}; run npm ci --ignore-scripts`,
      );
    const license = fs
      .readFileSync(path.join(root, file, "LICENSE"), "utf8")
      .trim();
    return { file, entry, meta, license };
  });
for (const field of ["dependencies", "devDependencies"]) {
  const declared = workspace[field] || {},
    recorded = lock.packages[""][field] || {};
  if (
    Object.keys(declared).length !== Object.keys(recorded).length ||
    Object.entries(declared).some(
      ([name, version]) => recorded[name] !== version,
    )
  )
    throw Error("Workspace manifest differs from lock: " + field);
}
const byName = new Map(rows.map((row) => [row.meta.name, row]));
if (byName.size !== rows.length)
  throw Error(
    "Nested dependency versions need an explicit notices classification",
  );
const runtime = new Set();
function visit(name) {
  if (runtime.has(name)) return;
  const row = byName.get(name);
  if (!row) throw Error(`Missing locked dependency: ${name}`);
  runtime.add(name);
  for (const dep of Object.keys(row.meta.dependencies || {})) visit(dep);
}
for (const [name, version] of Object.entries(plugin.dependencies || {})) {
  if (byName.get(name)?.meta.version !== version)
    throw Error(`Plugin pin differs from workspace lock: ${name}`);
  visit(name);
}
const link = (row) =>
  `[\`${row.meta.name}\`](https://www.npmjs.com/package/${row.meta.name}/v/${row.meta.version})`;
function table(items) {
  return [
    "| Package | Locked version | License |",
    "| --- | --- | --- |",
    ...items.map(
      (row) => `| ${link(row)} | ${row.meta.version} | ${row.meta.license} |`,
    ),
  ].join("\n");
}
const direct = rows.filter((row) =>
  Object.hasOwn(plugin.dependencies || {}, row.meta.name),
);
const transitive = rows.filter(
  (row) =>
    runtime.has(row.meta.name) &&
    !Object.hasOwn(plugin.dependencies || {}, row.meta.name),
);
const repository = rows.filter(
  (row) =>
    !runtime.has(row.meta.name) &&
    Object.hasOwn(workspace.dependencies || {}, row.meta.name),
);
const development = rows.filter(
  (row) =>
    !runtime.has(row.meta.name) &&
    !Object.hasOwn(workspace.dependencies || {}, row.meta.name),
);
if (development.some((row) => row.entry.dev !== true))
  throw Error(
    "Unclassified repository runtime dependency; review the inventory sections",
  );
const texts = new Map();
for (const row of rows) {
  const key = row.meta.license + "\n" + row.license;
  if (!texts.has(key)) texts.set(key, []);
  texts.get(key).push(row);
}
const sections = [
  "<!-- Generated by tools/third-party-notices.mjs; run npm run notices:generate after npm ci --ignore-scripts. -->",
  "# Third-Party Notices",
  "This project is licensed under [MIT](LICENSE). The third-party software below retains its own licenses and copyright notices.",
  "This inventory covers the production and development npm closure in the repository [package-lock.json](https://github.com/lcy0121/dsh-plugin-compat-check/blob/main/package-lock.json), checked against installed package metadata and license files. Plugin direct pins are checked against [plugin/package.json](https://github.com/lcy0121/dsh-plugin-compat-check/blob/main/plugin/package.json). Versions describe this checkout: fresh plugin installations also resolve the upstream packages' transitive ranges, so their installed license files remain authoritative.",
  "## Plugin runtime dependencies",
  table(direct),
  "### Transitive runtime dependencies",
  table(transitive),
  "## Repository runtime dependencies",
  "These packages support repository-only tools and are not declared as npm plugin runtime dependencies.",
  table(repository),
  "## Development-only dependencies",
  table(development),
  "Prettier also distributes its own bundled dependencies under MIT, ISC, BSD-3-Clause, BSD-2-Clause and Apache-2.0. Their individual notices are preserved in the installed `prettier/THIRD-PARTY-NOTICES.md`; the Prettier MIT license below does not replace those terms. Prettier is not shipped in this plugin.",
  "## Host-provided software and test inputs",
  "DeepSeek Harness and React are supplied by the host, not bundled here. The API catalog snapshots record their DSH source/version in `_source`; the upstream project is [DeepSeek Harness](https://github.com/deepseek-ai/deepseek-harness), licensed under [MIT](https://github.com/deepseek-ai/deepseek-harness/blob/master/LICENSE). External Node.js, Python, pnpm and Chrome installations retain their respective notices. Real-plugin acceptance downloads separately identified npm artifacts into private test directories; those artifacts are not redistributed as repository fixtures or inside this npm package.",
  "## License texts",
  ...Array.from(
    texts.values(),
    (items) =>
      `### ${items.map((row) => `${row.meta.name}@${row.meta.version}`).join(", ")} (${items[0].meta.license})\n\n${items[0].license
        .split("\n")
        .map((line) => (line ? "> " + line : ">"))
        .join("\n")}`,
  ),
  "## Maintenance",
  "Run `npm ci --ignore-scripts`, then `npm run notices:generate` after dependency or license changes. `npm run notices:check` verifies the committed text without changing it. Prepack copies the source notice into the plugin tarball; each separately installed dependency retains its own license files. This document follows the section structure of the [DSH third-party inventory](https://github.com/deepseek-ai/deepseek-harness/blob/master/THIRD_PARTY_NOTICES.md), with this repository's dependency set.",
];
const text = sections.join("\n\n") + "\n",
  file = path.join(root, "THIRD_PARTY_NOTICES.md");
if (process.argv.includes("--check")) {
  if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== text)
    throw Error("Stale THIRD_PARTY_NOTICES.md; run npm run notices:generate");
  console.log(`Third-party notices checked: ${rows.length} locked packages`);
} else {
  fs.writeFileSync(file, text);
  console.log(
    `Generated THIRD_PARTY_NOTICES.md: ${rows.length} locked packages`,
  );
}
